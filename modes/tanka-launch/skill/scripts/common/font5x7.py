def draw(img, x, y, text, scale=2, color=(255, 255, 255), bg=(0, 0, 0)):
    """draw `text` (upper-cased) into an HxWx3 uint8 array at (x, y), on a dark box"""
    text = str(text).upper(); w = len(text) * 6 * scale + 2 * scale; h = 9 * scale
    H, Wd = img.shape[:2]; img[max(0, y):min(H, y + h), max(0, x):min(Wd, x + w)] = bg
    for k, ch in enumerate(text):
        rows = G.get(ch, G[' ']); ox = x + scale + k * 6 * scale
        for r, bits in enumerate(rows):
            for c in range(5):
                if bits >> (4 - c) & 1:
                    y0, x0 = y + scale + r * scale, ox + c * scale
                    img[max(0, y0):min(H, y0 + scale), max(0, x0):min(Wd, x0 + scale)] = color
    return img
